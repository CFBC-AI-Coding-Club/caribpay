// pm2 definition for the FALLBACK demo — the wallet prototype tagged
// v0.1.0-wallet-demo, kept running through the overlay-switch pivot.
//
// This is deliberately a separate file from ecosystem.config.cjs so the
// fallback can be started, stopped and restarted without touching the live
// pivot processes, and so a mistake in one cannot take down the other.
//
// It must stay isolated from the pivot on all three stateful resources:
//
//   Postgres  caribpay_demo   — the pivot's migration 0005 DROPs the wallets
//                               table. Sharing a database destroys this build.
//   Redis     db index 3      — BullMQ keys are prefixed "bull" in both trees;
//                               on a shared index the two settlement workers
//                               would consume each other's jobs.
//   Port      3001            — Caddy routes demo.<host> here.
//
// Setup is in deploy/fallback.md.

const BUN = process.env.BUN_PATH || `${process.env.HOME}/.bun/bin/bun`;

// A git worktree checked out at the tag, so the fallback source cannot drift
// as the pivot branch moves underneath it.
const ROOT = process.env.FALLBACK_ROOT || `${process.env.HOME}/caribpay-fallback`;

const env = {
  NODE_ENV: "production",
  PORT: "3001",
  DATABASE_URL: "postgresql://caribpay:caribpay@localhost:5432/caribpay_demo",
  REDIS_URL: "redis://localhost:6379/3",
  // Same secret both processes, or QRs generated by one fail to verify in the
  // other. Independent of the pivot's secret.
  QR_HMAC_SECRET: process.env.FALLBACK_QR_HMAC_SECRET || "fallback-demo-qr-secret",
  JWT_ACCESS_SECRET: process.env.FALLBACK_JWT_SECRET || "fallback-demo-access-secret",
  // Keep the settlement delay at the demo default (random 2-5s) and failures off.
  MOCK_SETTLEMENT_FAILURES: "false",
};

module.exports = {
  apps: [
    {
      name: "caribpay-fallback-api",
      cwd: ROOT,
      script: "apps/api/src/index.ts",
      interpreter: BUN,
      env: { ...env, WORKER_IN_PROCESS: "false" },
      max_restarts: 10,
      restart_delay: 2000,
    },
    {
      name: "caribpay-fallback-worker",
      cwd: ROOT,
      script: "apps/api/src/workers/index.ts",
      interpreter: BUN,
      env,
      max_restarts: 10,
      restart_delay: 2000,
    },
  ],
};
